"""Build publication LaTeX table for ADNI CDRSB cognitive progression results from saved CSVs."""

from pathlib import Path
import pandas as pd

RES = Path(__file__).resolve().parent.parent / "paper" / "results"


def build_cdrsb_table(
    repeated_csv=RES / "adni_cdrsb_repeated_summary.csv",
    single_csv=RES / "rapid_adni_cdrsb.csv",
    out_tex=RES / "cdrsb_cognitive_table.tex",
):
    rep = pd.read_csv(repeated_csv).set_index("method")
    sng = pd.read_csv(single_csv).set_index("method")

    def _rep_row(k, bold=False):
        if k not in rep.index:
            return "---", "---", "---"
        r = rep.loc[k]
        lin = f"{r['r2_linear_mean']:.3f} $\\pm$ {r['r2_linear_sd']:.3f}"
        rf = f"{r['r2_forest_mean']:.3f} $\\pm$ {r['r2_forest_sd']:.3f}"
        if k == "PCA":
            drf = "0.000"
        else:
            sign = "+" if r["dr2_forest_vs_PCA"] >= 0 else ""
            drf = f"${sign}{r['dr2_forest_vs_PCA']:.3f}$ [{r['dr2_forest_ci_lo']:.3f}, {r['dr2_forest_ci_hi']:.3f}]"
        if bold:
            lin = f"\\textbf{{{lin}}}"
            rf = f"\\textbf{{{rf}}}"
            drf = f"\\textbf{{{drf}}}"
        return lin, rf, drf

    def _sng_row(k, bold=False):
        if k not in sng.index:
            return "---", "---", "---"
        r = sng.loc[k]
        lin = f"{r['r2_linear']:.3f}"
        rf = f"{r['r2_forest']:.3f}"
        lobe = "---" if pd.isna(r["lobe_overlap"]) else f"{r['lobe_overlap']:.3f}"
        if bold:
            lin = f"\\textbf{{{lin}}}"
            rf = f"\\textbf{{{rf}}}"
            if lobe != "---":
                lobe = f"\\textbf{{{lobe}}}"
        return lin, rf, lobe

    rows_spec = [
        ("Covariates Baseline", "Covariates only", "Covariates Baseline", False),
        ("Dense PCA ($k=5$)", "PCA", "PCA (k=5)", False),
        (r"\midrule", None, None, False),
        ("NSA-Flow Anchored ($w=0.5$)", "NSA anchored w=0.5", "NSA-Flow (anchored, w=0.5)", False),
        ("NSA-Flow Data ($w=0.5$)", "NSA data w=0.5", "NSA-Flow (data, w=0.5)", False),
        ("NSA-Flow Signed ($w=0.5$)", "NSA signed w=0.5", "NSA-Flow (signed, w=0.5)", False),
        ("\\textbf{NSA-Flow Consol ($w=0.5$)}", "NSA consolidated w=0.5", "NSA-Flow (consolidated, w=0.5)", True),
    ]

    lines = []
    for label, rk, sk, bold in rows_spec:
        if rk is None:
            lines.append(label)
            continue
        c1, c2, c3 = _rep_row(rk, bold=bold)
        c4, c5, c6 = _sng_row(sk, bold=bold)
        lines.append(f"{label} & {c1} & {c2} & {c3} & {c4} & {c5} & {c6} \\\\")

    body = "\n".join(lines)
    rc = rep.loc["NSA consolidated w=0.5"]
    sc = sng.loc["NSA-Flow (consolidated, w=0.5)"]
    sp = sng.loc["PCA (k=5)"]

    tex = f"""% auto-generated by experiments/build_cdrsb_tables.py
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lcccccc}}
\\toprule
& \\multicolumn{{3}}{{c}}{{\\textbf{{20 Repeated 80/20 Splits}}}} & \\multicolumn{{3}}{{c}}{{\\textbf{{Primary 80/20 Split}}}} \\\\
\\cmidrule(lr){{2-4}} \\cmidrule(lr){{5-7}}
\\textbf{{Method}} & Linear $R^2$ & Forest $R^2$ & $\\Delta R^2_{{\\text{{PCA}}}}$ Forest [95\\% CI] & Linear $R^2$ & Forest $R^2$ & Lobe Overlap \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Continuous clinical cognitive progression on ADNI: predicting Clinical Dementia Rating Sum of Boxes (CDRSB) from cortical thickness networks ($n=307, p=66, k=5$) after adjusting for baseline covariates (age, sex, education, APOE4) strictly inside each training split. Across 20 repeated 80/20 splits, Consolidated Signed NSA-Flow improves over PCA by $+{rc['dr2_linear_vs_PCA']:.3f}$ (95\\% CI $[{rc['dr2_linear_ci_lo']:.3f}, {rc['dr2_linear_ci_hi']:.3f}]$) under a linear model and $+{rc['dr2_forest_vs_PCA']:.3f}$ (95\\% CI $[{rc['dr2_forest_ci_lo']:.3f}, {rc['dr2_forest_ci_hi']:.3f}]$) under Random Forests (primary split: Forest $R^2 = {sc['r2_forest']:.3f}$ vs.\\ ${sp['r2_forest']:.3f}$, Linear $R^2 = {sc['r2_linear']:.3f}$ vs.\\ ${sp['r2_linear']:.3f}$), with zero lobe overlap.}}
\\label{{tab:cdrsb_progression}}
\\end{{table}}
"""
    with open(out_tex, "w") as f:
        f.write(tex)
    print(f"Successfully generated {out_tex}")


if __name__ == "__main__":
    build_cdrsb_table()
