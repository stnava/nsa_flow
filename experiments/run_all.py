def save(df, name):
    df.to_csv(RES / f"{name}.csv", index=False)
    print(f"    wrote results/{name}.csv  ({len(df)} rows)")
    return df


_TEX_SPECIAL = {"_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#"}


def _escape_cells(df):
    r"""Escape LaTeX specials in string *data* only.

    Column names are written by hand and may contain intentional math, so they
    must not be escaped; pandas' ``escape=True`` would turn ``$w$`` into
    ``\$w\$``.
    """
    out = df.copy()
    for c in out.columns:
        if out[c].dtype == object:
            out[c] = out[c].astype(str).apply(
                lambda v: "".join(_TEX_SPECIAL.get(ch, ch) for ch in v))
    return out


def tex(df, name, caption, label, floatfmt="%.3f", **kw):
    body = _escape_cells(df).to_latex(index=False, escape=False,
                                      float_format=floatfmt,
                                      column_format=kw.pop("column_format", None), **kw)
    (RES / f"{name}.tex").write_text(
        f"% auto-generated by experiments/run_all.py\n"
        f"\\begin{{table}}[t]\n\\centering\n\\small\n{body}"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")
    print(f"    wrote results/{name}.tex")


# ----------------------------------------------------------------- E0: functionals
def fig_functionals():
    """Why D and not the v1 defect: zero sets, blindness to imbalance, collapse."""
    import torch
    from nsa_flow import gram, stiefel_defect
    torch.set_default_dtype(torch.float64)
    torch.manual_seed(0)

    def old(Y):
        S = gram(Y)
        return ((S * S).sum() - S.diagonal().pow(2).sum()) / Y.pow(2).sum() ** 2

    fig, ax = plt.subplots(1, 3, figsize=(9.6, 2.9))

    # (a) orthogonal columns, one rescaled: v1 sees nothing, D sees it
    Q = torch.linalg.qr(torch.randn(60, 6))[0]
    rs = np.linspace(1, 8, 60)
    do, dn = [], []
    for r in rs:
        s = torch.ones(6, dtype=torch.float64)
        s[-1] = float(r)
        do.append(old(Q * s).item())
        dn.append(stiefel_defect(Q * s).item())
    ax[0].plot(rs, do, color=GREY, lw=2, label="v1 defect")
    ax[0].plot(rs, dn, color=BLUE, lw=2, label="$D$")
    ax[0].set_xlabel("norm of one column ($\\times$ others)")
    ax[0].set_ylabel("value")
    ax[0].set_title("(a) columns stay orthogonal", fontsize=9)
    ax[0].legend()

    # (b) rank collapse: v1 reaches zero, D has a floor
    k = 6
    ranks = list(range(1, k + 1))
    obs_old, obs_new = [], []
    for r in ranks:
        lo_o, lo_n = np.inf, np.inf
        for _ in range(400):
            Y = torch.randn(60, r) @ torch.randn(r, k)
            lo_o, lo_n = min(lo_o, old(Y).item()), min(lo_n, stiefel_defect(Y).item())
        Qd = torch.linalg.qr(torch.randn(60, k))[0].clone()
        Qd[:, r:] = 0.0
        obs_old.append(min(lo_o, old(Qd).item()))
        obs_new.append(lo_n)
    ax[1].plot(ranks, obs_old, "o-", color=GREY, lw=2, label="v1 defect")
    ax[1].plot(ranks, obs_new, "o-", color=BLUE, lw=2, label="$D$")
    ax[1].plot(ranks, [1 / r - 1 / k for r in ranks], ":", color=RED, lw=1.6,
               label="$1/r-1/k$ (bound)")
    ax[1].set_xlabel("rank $r$ of $Y$")
    ax[1].set_ylabel("minimum attainable")
    ax[1].set_title("(b) rank-deficient matrices", fontsize=9)
    ax[1].legend()

    # (c) D = 1/EffectiveRank - 1/k
    Ys = [torch.rand(60, 6) * torch.rand(6) ** t for t in np.linspace(0, 6, 220)]
    er = [(6 / (6 * stiefel_defect(Y).item() + 1)) for Y in Ys]
    ax[2].scatter([stiefel_defect(Y).item() for Y in Ys], er, s=7, color=BLUE, alpha=0.7)
    ax[2].set_xlabel("$D(Y)$")
    ax[2].set_ylabel("effective rank")
    ax[2].set_title("(c) $D = 1/\\mathrm{ER} - 1/k$", fontsize=9)

    fig.tight_layout()
    fig.savefig(FIGS / "functionals.pdf")
    plt.close(fig)
    print("    wrote figs/functionals.pdf")


