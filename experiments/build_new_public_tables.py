"""Build publication LaTeX table for new public benchmarks from saved JSON results."""

import json
import os


def _fmt(d, name, key, fmt="{:.3f}", scale=1.0):
    if name not in d:
        return "---"
    val = d[name]["raw"][key] * scale
    return fmt.format(val)


def build_latex_table(benchmarks_json="paper/results/new_public_data_benchmark_results.json",
                      out_tex="paper/results/new_public_benchmarks_table.tex"):
    with open(benchmarks_json, "r") as f:
        data = json.load(f)

    tec = {r["Method"]: r for r in data["tecator"]}
    son = {r["Method"]: r for r in data["sonar"]}
    pros = {r["Method"]: r for r in data["prostate"]}

    rows = [
        ("Dense PCA", "PCA", False),
        ("NMF (Non-negative)", "NMF", False),
        (r"\midrule", None, False),
        (r"NSA-Flow Nonneg ($w=0.0$)", "NSA-Flow Nonneg (w=0.0)", False),
        (r"NSA-Flow Nonneg ($w=0.5$)", "NSA-Flow Nonneg (w=0.5)", False),
        (r"NSA-Flow Signed ($w=0.0$)", "NSA-Flow Signed (w=0.0)", False),
        (r"NSA-Flow Signed ($w=0.5$)", "NSA-Flow Signed (w=0.5)", False),
        (r"NSA-Flow Consol ($w=0.5$)", "NSA-Flow Consol (w=0.5)", True),
    ]

    body_lines = []
    for label, key, bold in rows:
        if key is None:
            body_lines.append(label)
            continue
        t_r2 = _fmt(tec, key, "r2_lin_mean")
        t_def = _fmt(tec, key, "defect_mean")
        s_auc = _fmt(son, key, "auc_mean")
        s_bacc = _fmt(son, key, "bacc_mean")
        p_bacc = _fmt(pros, key, "bacc_mean")
        p_sp = _fmt(pros, key, "sparsity_mean", fmt="{:.1f}\\%", scale=100.0)
        cells = [label, t_r2, t_def, s_auc, s_bacc, p_bacc, p_sp]
        if bold:
            cells = [cells[0]] + [f"\\textbf{{{c}}}" if c != "---" else c for c in cells[1:]]
        body_lines.append(" & ".join(cells) + r" \\")

    sp_consol = _fmt(pros, "NSA-Flow Consol (w=0.5)", "sparsity_mean", fmt="{:.1f}\\%", scale=100.0)
    body_str = "\n".join(body_lines)

    tex = f"""% auto-generated by experiments/build_new_public_tables.py
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lcccccc}}
\\toprule
& \\multicolumn{{2}}{{c}}{{\\textbf{{Tecator NIR ($k=5$)}}}} & \\multicolumn{{2}}{{c}}{{\\textbf{{Sonar Chirps ($k=6$)}}}} & \\multicolumn{{2}}{{c}}{{\\textbf{{Prostate Cancer ($k=6$)}}}} \\\\
\\cmidrule(lr){{2-3}} \\cmidrule(lr){{4-5}} \\cmidrule(lr){{6-7}}
\\textbf{{Method}} & Ridge $R^2$ & Defect $D$ & ROC-AUC & Bal.~Acc. & Bal.~Acc. & Disjoint Sparsity \\\\
\\midrule
{body_str}
\\bottomrule
\\end{{tabular}}
\\caption{{Cross-validated benchmark evaluation across three public datasets: Tecator NIR spectroscopy ($n=240, p=100$, predicting chemical fat \\%), Sonar acoustic frequency returns ($n=208, p=60$, classifying mines vs.\\ rocks), and Prostate cancer microarray ($n=102, p=12{{,}}600$, top 2000 in-fold genes classifying tumor vs.\\ normal). All feature scaling, gene selection, and representation learning are executed strictly inside each fold. Defect $D = \\|G - I/k\\|_F^2 / (1 - 1/k)$ measures deviation from the scaled Stiefel manifold. Consolidated NSA-Flow attains {sp_consol} exact zero loadings with zero lobe overlap while matching or slightly exceeding PCA accuracy.}}
\\label{{tab:new_public_benchmarks}}
\\end{{table}}
"""
    os.makedirs(os.path.dirname(out_tex), exist_ok=True)
    with open(out_tex, "w") as f:
        f.write(tex)
    print(f"Successfully generated {out_tex}")


if __name__ == "__main__":
    build_latex_table()
