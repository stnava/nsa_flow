"""Rebuild every LaTeX table in paper/results/ from the saved CSVs.

Kept separate from ``run_all.py`` so that a formatting fix does not require
re-running the experiments -- the CSVs are the results, the tables are a view of
them.

    python experiments/build_tables.py
"""
from pathlib import Path

import pandas as pd

RES = Path(__file__).resolve().parent.parent / "paper" / "results"

_TEX_SPECIAL = {"_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#"}


def _escape_cells(df):
    r"""Escape LaTeX specials in string *data* only; column names are hand-written.

    pandas >= 3 gives string columns a dedicated ``str`` dtype, so testing
    ``dtype == object`` silently matches nothing and leaves specials raw.
    """
    out = df.copy()
    for c in out.columns:
        if not pd.api.types.is_numeric_dtype(out[c]):
            out[c] = out[c].astype(str).apply(
                lambda v: "".join(_TEX_SPECIAL.get(ch, ch) for ch in v))
    return out


# Column names are emitted unescaped so they can carry math, so every column
# reaching LaTeX needs a display name free of underscores.
_PRETTY = {
    "auc": "AUC", "auc_sd": "AUC sd", "acc": "acc", "acc_sd": "acc sd",
    "dAUC_vs_PCA": "$\\Delta$AUC vs PCA", "us_per_iter": "$\\mu$s/iter",
    "mflop": "MFLOP", "max_rel_spread": "max rel.\\ spread",
    "n_restarts": "restarts", "best_lr": "best lr", "svd_finite": "SVD finite",
    "svd_nans": "SVD NaNs", "polar_finite": "polar finite",
    "polar_nans": "polar NaNs", "eff_rank": "eff.\\ rank",
    "n_empty": "empty comps", "support_f1": "support F1",
    "rel_spread": "rel.\\ spread", "w_nominal": "$w$ nominal",
    "v1_effective": "v1 realised", "v1_predicted": "v1 predicted",
    "v2_effective": "v2 realised", "fidelity_type": "fidelity",
    "orth_type": "orthogonality", "fid_ratio": "fid/target",
    "orth_ratio": "orth/target", "ari_truth": "ARI vs truth",
    "ari_kmeans": "ARI vs $k$-means", "time_sec": "seconds",
}


def _pretty(df):
    """Rename any column whose name would be illegal in LaTeX text mode."""
    out = df.rename(columns=_PRETTY)
    bad = [c for c in out.columns if any(ch in str(c) for ch in "_%&#")]
    if bad:
        raise ValueError(f"columns need display names in _PRETTY: {bad}")
    return out


def tex(df, name, caption, label, floatfmt="%.3f"):
    body = _escape_cells(_pretty(df)).to_latex(index=False, escape=False,
                                               float_format=floatfmt)
    (RES / f"{name}.tex").write_text(
        "% auto-generated by experiments/build_tables.py\n"
        f"\\begin{{table}}[t]\n\\centering\n\\small\n{body}"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\end{{table}}\n")
    print(f"  wrote {name}.tex")


def _csv(name):
    f = RES / f"{name}.csv"
    return pd.read_csv(f) if f.exists() else None


def build():
    # ---- E1 refinement
    d = _csv("e1_refinement")
    if d is not None:
        tex(d, "e1_table",
            "NSA-Flow as a refinement operator: each base loading matrix against "
            "its best refinement, on a planted non-negative disjoint basis "
            "($p=60$, $k=6$, $n=300$), averaged over 4 noise levels $\\times$ 10 "
            "replicates. \\texttt{cos} is mean matched $|\\cos|$ to the truth, "
            "\\texttt{F1} is support F1, \\texttt{overlap} is the mean number of "
            "extra components an active feature loads on. Refinement improves "
            "every base on every metric.",
            "tab:recovery")

    # ---- E2 calibration
    d = _csv("e2_term_calibration")
    if d is not None:
        v1 = (d[d.version == "v1"].groupby(["fidelity_type", "orth_type"])
              [["fid_ratio", "orth_ratio"]].mean().reset_index()
              .rename(columns={"fidelity_type": "fidelity",
                               "orth_type": "orthogonality",
                               "fid_ratio": "fid/target",
                               "orth_ratio": "orth/target"}))
        tex(v1, "e2_calibration_table",
            "v1 energy terms relative to their own calibration targets, averaged "
            "over problem sizes and $w$. A value of 1 means the term is "
            "calibrated as intended. Only \\texttt{basic}/"
            "\\texttt{scale\\_invariant} is correct; the shipped default "
            "(\\texttt{scale\\_invariant}/\\texttt{scale\\_invariant}) "
            "under-weights fidelity by a factor of $pk$.",
            "tab:calibration", floatfmt="%.3g")

    d = _csv("e2_effective_fraction")
    if d is not None:
        tex(d.rename(columns={"w_nominal": "$w$ nominal", "v1_effective": "v1 realised",
                              "v1_predicted": "v1 predicted",
                              "v2_effective": "v2 realised"}),
            "e2_fraction_table",
            "Realised blend fraction against the nominal $w$. v1 blended against "
            "a unit-norm polar factor, so the realised fraction follows "
            "$w\\sqrt{k}/(w\\sqrt{k}+(1-w)\\lVert Y\\rVert_F)$ and shrinks with "
            "$p$. Blending against the projection $P(Y)$ makes $w$ exact.",
            "tab:fraction", floatfmt="%.4f")

    # ---- E3 clustering
    d = _csv("e3_best")
    if d is not None:
        tex(d, "e3_table",
            "Agreement of the induced feature partition with the planted truth "
            "and with $k$-means run directly on the features, over 10 replicates "
            "$\\times$ 3 noise levels. $k$-means recovers the planted partition "
            "exactly here, so the two columns coincide for it. Refinement improves "
            "the NMF partition and leaves the already-exact sparse PCA partition "
            "intact, but slightly degrades the PCA partition: driving $D$ to zero "
            "from a poor basis can commit to the wrong partition.",
            "tab:clustering")

    # ---- E4 Golub
    d = _csv("e4_golub")
    if d is not None:
        cols = [c for c in ["method", "auc", "auc_sd", "dAUC_vs_PCA", "acc",
                            "acc_sd", "defect", "sparsity", "overlap"] if c in d]
        tex(d[cols], "e4_table",
            "Golub leukemia (ALL vs AML, $n=72$, $k=5$, top 2000 genes selected "
            "inside each fold): repeated stratified 5-fold CV, all fitting inside "
            "the training fold. \\texttt{overlap} is the mean number of extra "
            "components each active gene loads on; 0 means disjoint gene "
            "signatures.",
            "tab:golub")

    # ---- E5 ADNI
    d = _csv("e5_adni")
    if d is not None:
        auc = d.pivot_table(index="method", columns="task", values="auc")
        ovl = d.pivot_table(index="method", values="overlap")
        tab = pd.concat([auc, ovl], axis=1).reset_index()
        tex(tab, "e5_table",
            "ADNI (right-hemisphere DKT grey-matter volumes, $k=5$): "
            "cross-validated AUC by task, age and sex regressed out inside each "
            "fold, with mean support overlap in the last column. $n$: 418 CN/DEM, "
            "622 CN/MCI, 588 MCI/DEM.",
            "tab:adni")

    # ---- E6
    d = _csv("e6_svd_gradient")
    if d is not None:
        tex(d, "e6_svd_table",
            "Backward pass through the polar factor. Differentiating "
            "\\texttt{torch.linalg.svd} divides by $\\sigma_i^2-\\sigma_j^2$ and "
            "returns NaN for every entry at repeated singular values --- exactly "
            "what \\texttt{nn.init.orthogonal\\_} produces. The Sylvester "
            "derivative divides by $h_i+h_j>0$.",
            "tab:svd", floatfmt="%.0f")

    d = _csv("e6_lr_pathology")
    if d is not None:
        tex(d, "e6_lr_table",
            "v1 learning-rate estimates. The candidate grid depends only on "
            "\\texttt{aggression}, so every strategy returns the same constant "
            "regardless of $p$, $k$, the data or the gradient. The shipped "
            "default was \\texttt{bayes}.",
            "tab:lr", floatfmt="%.6g")

    d = _csv("e6_end_to_end")
    if d is not None:
        cols = [c for c in ["version", "p", "k", "w", "seconds", "iters", "defect",
                            "fidelity"] if c in d]
        tex(d[cols], "e6_speed_table",
            "End-to-end cost on matched problems, both scored with the same "
            "normalised $D$. v1 is given a hand-set step of $10^{-3}$ because its "
            "default returns $\\approx 95.9$ and diverges, and is capped at 500 "
            "iterations.",
            "tab:speed", floatfmt="%.4g")

    d = _csv("e6_uniqueness")
    if d is not None:
        u = (d.groupby("w").agg(restarts=("n_restarts", "max"),
                                max_rel_spread=("rel_spread", "max")).reset_index())
        tex(u, "e6_uniqueness_table",
            "Relative spread of the optimal energy over 24 random restarts, worst "
            "case across 4 problems. For $w\\le0.9$ the optimum is unique to "
            "machine precision; mild multimodality appears only as $w\\to1$, "
            "where the problem becomes combinatorial.",
            "tab:uniqueness", floatfmt="%.3g")

    # Rebuild new public benchmarks table if JSON results are present
    try:
        from experiments.build_new_public_tables import build_latex_table
        build_latex_table()
    except Exception as e:
        print(f"Warning: could not rebuild new public benchmarks table: {e}")


if __name__ == "__main__":
    print(f"rebuilding tables in {RES}")
    build()
